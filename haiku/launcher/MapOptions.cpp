// frontend-qt6 ui/widget/mapContainer.cpp's options for generated maps
#include "MapOptions.h"
#include "Game.h"

#include <algorithm>

#include <MenuItem.h>
#include <PopUpMenu.h>

static BMenuField* list(const char* label, std::initializer_list<const char*> items)
{
	BPopUpMenu* menu = new BPopUpMenu("");
	for (const char* s : items)
		menu->AddItem(new BMenuItem(s, NULL));
	menu->ItemAt(0)->SetMarked(true);
	return new BMenuField(label, menu);
}

static int marked(BMenuField* f) { return std::max(0, (int)f->Menu()->IndexOf(f->Menu()->FindMarked())); }

MapOptions::MapOptions()
{
	size = list("Map size:", {"All", "Small", "Medium", "Large", "Cavern", "Wacky"});
	maze = list("Maze style:", {"Small tunnels", "Medium tunnels", "Large tunnels", "Small islands",
		"Medium islands", "Large islands"});
	feature = new BSlider("feature", "Feature size:", NULL, 1, 25, B_HORIZONTAL);
	feature->SetValue(12);
	feature->SetToolTip("Adjust the complexity of the generated map, or the distance between forts");
	seed = new BTextControl("Seed:", "", NULL);
	seed->SetToolTip("The map seed is the basis for all random values generated by the game. "
		"Leave it empty for a new one each game.");
}

// MAPGEN_REGULAR and MAPGEN_WFC pick a template by size, MAPGEN_MAZE and MAPGEN_PERLIN by maze style
void MapOptions::Update(int mapgen)
{
	size->SetEnabled(mapgen == 0 || mapgen == 5);
	maze->SetEnabled(mapgen == 1 || mapgen == 2);
	feature->SetEnabled(mapgen >= 0);
}

std::string MapOptions::Seed() const
{
	return seed->Text()[0] ? seed->Text() : new_seed();
}

void MapOptions::Config(int mapgen, std::string& before, std::string& after) const
{
	add(before, "e$template_filter " + std::to_string(marked(size)));
	add(before, "e$feature_size " + std::to_string(feature->Value()));
	if (mapgen == 1 || mapgen == 2)
		add(after, "e$maze_size " + std::to_string(marked(maze)));
}
