#!/usr/bin/env python3
"""gen-schemes.py: the Qt frontend's predefined game schemes as a C table.

    python3 haiku/tools/gen-schemes.py > haiku/launcher/schemes.h

Reads frontend-qt6/model/gameSchemeModel.cpp: each scheme is a run of 45
QVariant(...) values (name, 25 flags, 18 numbers, script parameter)."""
import re
import sys

src = open("frontend-qt6/model/gameSchemeModel.cpp").read()
names = re.findall(r'QStringLiteral\("([^"]+)"\)', src[src.index("predefSchemesNames ="):src.index("numberOfDefaultSchemes =")])
values = re.findall(r"<<\s*(?:QVariant\(([^)]*)\)|predefSchemesNames\[\d+\])", src)
schemes = [values[i:i + 45] for i in range(0, len(values), 45)]
assert len(values) % 45 == 0 and len(schemes) == len(names), (len(values), len(names))
print("// Generated by haiku/tools/gen-schemes.py from frontend-qt6; don't edit.")
print("struct Scheme { const char* name; int v[44]; const char* scriptparam; };")
print("static const Scheme kSchemes[] = {")
for name, s in zip(names, schemes):
    nums = [("1" if v == "true" else "0" if v == "false" else v) for v in s[1:44]]
    assert all(re.fullmatch(r"-?\d+", n) for n in nums), (name, nums)
    param = s[44]
    print('\t{"%s", {0, %s}, %s},' % (name, ", ".join(nums), param if param else "NULL"))
print("};")
